# Operadores quantitativos relacionados a números que retornam valor bool ( True or False )
2 > 1 # Maior
1 < 2 # Menor
2 >= 2 # Maior ou Igual
2 <= 2 # Menor ou Igual 
2 == 2 # Igual
2 != 1 # Diferente

# Operadores de atribuição funcionam como forma de resumo a operações
num = 10 # num = num
num += 1 # num = num + 1
num -= 1 # num = num - 1
num *= 2 # num = num * 2
num /= 2 # num = num / 2
num **= 2 # num = num ** 2
num //= 2 # num = num // 2
num %= 2 # num = num % 2