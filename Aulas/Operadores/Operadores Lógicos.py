# Utilizamos dentro das condições os operadores lógicos and, or, not, in e not in
if 'a' and 'b' in 'ab':  # Utilizamos o and para requisitar mais condições
    print('Estão em "ab"')
if 'a' or 1 == str():  # Utilizamos o or para disponibilizar mais condições
    print('Pelo menos um é string')
if 'a' not in 'b':  # Utilizamos o not para checar se determinado dado não é tal coisa
    print('Não está em "b"')
if 1 in range(1, 10):  # Utilizamos in para checar se determinado valor está em tal coisa
    print('Está no range 1-10')
if 1 not in range (2, 10):  # Utilizamos not in para checar se determinado valor não está em tal coisa
    print('Não está no range 2-10')