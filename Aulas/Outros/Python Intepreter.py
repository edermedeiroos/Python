# Comando executados no terminal do python
"""
• python -- | Exibe a versão instalada do python
• python mód.py | Executa o módulo (arquivo) digitado .py
• python -m mód | Executa uma biblioteca como módulo
• python -c 'command' | Executa o comando entre aspas no cmd
• python -i mód.py | Carrega o módulo digitado .py
• python -m venv 'Nome do Ambiente' | Cria um ambiente virtual com o módulo venv
• gcm python | Mostra o diretório que está instalado o python
• pip freeze | Mostra os módulos instalados em determinado ambiente virtual
• pip freeze > requierements.txt | Atualiza ou cria um arquivo txt utilizado para exibir os módulos e versões requiridas de um ambiente virtual
• pip install pip -- upgrade | Atualiza as versões dos módulos instalados
"""